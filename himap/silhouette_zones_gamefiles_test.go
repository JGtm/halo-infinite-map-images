func TestSilhouettePrimeSurLesZonesCatalyst(t *testing.T) {
	racine := racineDuJeu(t)
	ctx := context.Background()
	maillage, _, err := ChargeMaillageNatif(ctx, racine, "catalyst")
	if err != nil {
		t.Fatal(err)
	}
	r, b, err := CuitCarteNative(ctx, OptionsCuisson{
		RacineDeploy: racine,
		CheminModule: moduleDuJeu(t, "pc", "catalyst"),
		Ancres:       ancresCatalyst,
		Echelle:      0.038,
		CibleCadrePx: CibleCadrePx,
		EcreteToits:  true, PlafondArene: 4, CombleTrous: true,
		ZonesNommees: zonesCatalyst, RogneAuxZones: true,
		BoiteUtile: [4]float64{-20.5, -27, 21, 27},
		Navmesh:    OptionsNavmesh{Maillage: maillage, Rogne: true, Mode: ModeSilhouette},
	})
	if err != nil {
		t.Fatal(err)
	}
	// La plate-forme du sud : x de -3,2 a 3,2 et y de -26,2 a -19,6, 21 300 cellules a 3,8 cm.
	sud := 0
	for j := 0; j < r.NY; j++ {
		y := r.Min[1] + (float64(j)+0.5)*r.Cell
		for i := 0; i < r.NX; i++ {
			x := r.Min[0] + (float64(i)+0.5)*r.Cell
			if x >= -3.2 && x <= 3.2 && y >= -26.2 && y <= -19.6 && r.matiereEn(x, y) {
				sud++
			}
		}
	}
	t.Logf("catalyst : %d cellules sauvees par le plan, %d effacees par les zones, %d de matiere sur la plate-forme sud, ancres au sol %d/%d",
		b.CellulesSauveesParPlan, b.CellulesHorsZones, sud, b.AncresAvecSol, b.AncresDansLeCadre)
	if b.CellulesSauveesParPlan < 21000 {
		t.Errorf("%d cellules sauvees par le plan, attendu au moins 21 000 (la plate-forme du sud)", b.CellulesSauveesParPlan)
	}
	if sud < 21000 {
		t.Errorf("%d cellules de matiere sur la plate-forme du sud, attendu au moins 21 000", sud)
	}
	// Mesure du 2026-11-14 : sans la regle, 22 ancres au sol sur 29 et 5 148 cellules sur la plate-forme du sud.
	const sauvees, ancresAuSol, ancresDansLeCadre = 24123, 25, 29
	if b.CellulesSauveesParPlan != sauvees || b.AncresAvecSol != ancresAuSol || b.AncresDansLeCadre != ancresDansLeCadre {
		t.Errorf("sauvees %d, ancres au sol %d sur %d ; attendu %d, %d sur %d",
			b.CellulesSauveesParPlan, b.AncresAvecSol, b.AncresDansLeCadre, sauvees, ancresAuSol, ancresDansLeCadre)
	}
}
